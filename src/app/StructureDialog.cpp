namespace {

class SectionCard : public QFrame
{
public:
    SectionCard(const AgendaPoint &point, bool generated, QWidget *parent)
        : QFrame(parent)
        , number(Ui::label(QString(), nullptr, this))
        , badge(Ui::label(QString(), nullptr, this))
        , title(new QLineEdit(point.title, this))
        , minutes(new DurationEdit(this))
        , text(new QPlainTextEdit(point.sourceText, this))
        , keyPoints(new QPlainTextEdit(point.keyPoints.join(QLatin1Char('\n')), this))
        , up(button(Icons::Icon::ArrowUp, StructureDialog::tr("Move up")))
        , down(button(Icons::Icon::ArrowDown, StructureDialog::tr("Move down")))
        , remove(button(Icons::Icon::Close, StructureDialog::tr("Delete section")))
        , m_point(point)
    {
        setObjectName(QStringLiteral("card"));
        const Theme::Colors &c = Theme::colors();

        number->setFixedSize(26, 26);
        number->setAlignment(Qt::AlignCenter);
        number->setStyleSheet(QStringLiteral("background: %1; color: %2; border-radius: 13px; font-weight: 700;")
                                  .arg(Theme::css(c.button), Theme::css(c.accent)));
        QFont tf = title->font();
        tf.setPointSizeF(tf.pointSizeF() * 1.1);
        tf.setWeight(QFont::DemiBold);
        title->setFont(tf);
        title->setPlaceholderText(StructureDialog::tr("Section title"));
        minutes->setAllowZero(true);
        minutes->setSeconds(point.targetSeconds);
        minutes->setFixedWidth(minutes->sizeHint().width());
        text->setPlaceholderText(StructureDialog::tr("Your words for this section"));
        text->setFixedHeight(84);
        keyPoints->setPlaceholderText(StructureDialog::tr("Key points to get across, one per line"));
        keyPoints->setFixedHeight(64);
        setGenerated(generated);

        auto *head = new QHBoxLayout;
        head->setSpacing(8);
        head->addWidget(number);
        head->addWidget(title, 1);
        head->addWidget(badge);
        head->addWidget(minutes);
        head->addWidget(up);
        head->addWidget(down);
        head->addWidget(remove);

        auto *v = new QVBoxLayout(this);
        v->setContentsMargins(16, 12, 16, 14);
        v->setSpacing(8);
        v->addLayout(head);
        v->addWidget(Ui::label(StructureDialog::tr("TEXT"), "caption", this));
        v->addWidget(text);
        v->addWidget(Ui::label(StructureDialog::tr("KEY POINTS"), "caption", this));
        v->addWidget(keyPoints);

        auto edited = [this] { setGenerated(false); };
        QObject::connect(title, &QLineEdit::textEdited, this, edited);
        QObject::connect(text, &QPlainTextEdit::textChanged, this, [this, edited] {
            if (text->hasFocus())
                edited();
        });
        QObject::connect(keyPoints, &QPlainTextEdit::textChanged, this, [this, edited] {
            if (keyPoints->hasFocus())
                edited();
        });
        QObject::connect(minutes, &DurationEdit::secondsChanged, this, edited);
    }

    void setGenerated(bool generated)
    {
        const Theme::Colors &c = Theme::colors();
        badge->setText(generated ? StructureDialog::tr("AI") : StructureDialog::tr("Edited"));
        badge->setToolTip(generated ? StructureDialog::tr("Generated by SMILE") : StructureDialog::tr("Changed by you"));
        badge->setStyleSheet(QStringLiteral("background: %1; color: %2; border-radius: 8px; padding: 1px 8px; font-weight: 600;")
                                 .arg(Theme::css(generated ? c.button : c.track),
                                      Theme::css(generated ? c.accent : c.textSecondary)));
    }

    AgendaPoint point() const
    {
        AgendaPoint p = m_point;
        p.title = title->text().trimmed();
        p.targetSeconds = minutes->seconds();
        p.sourceText = text->toPlainText().trimmed();
        p.keyPoints.clear();
        for (const QString &line : keyPoints->toPlainText().split(QLatin1Char('\n'))) {
            QString t = line.trimmed();
            t.remove(QRegularExpression(QStringLiteral("^[•\\-*]\\s*")));
            if (!t.isEmpty())
                p.keyPoints << t;
        }
        return p;
    }

    QLabel *number;
    QLabel *badge;
    QLineEdit *title;
    DurationEdit *minutes;
    QPlainTextEdit *text;
    QPlainTextEdit *keyPoints;
    QPushButton *up, *down, *remove;

private:
    QPushButton *button(Icons::Icon icon, const QString &tip)
    {
        auto *b = new QPushButton(this);
        b->setObjectName(QStringLiteral("subtle"));
        b->setIcon(Icons::icon(icon, Theme::colors().textSecondary, 14));
        b->setToolTip(tip);
        b->setFixedSize(30, 30);
        b->setCursor(Qt::PointingHandCursor);
        return b;
    }
    AgendaPoint m_point;
};

} // namespace

StructureDialog::StructureDialog(const Agenda &sections, const QString &presentationType, bool fromAi, QWidget *parent)
    : QDialog(parent)
    , m_list(new QVBoxLayout)
    , m_summary(Ui::label(QString(), "secondary"))
{
    setWindowTitle(tr("Your speech, structured"));
    setObjectName(QStringLiteral("root"));
    setAttribute(Qt::WA_StyledBackground);
    resize(820, 760);
    const Theme::Colors &c = Theme::colors();

    QLabel *title = Ui::label(tr("Here's how SMILE structured your speech"), "pageTitle");
    QFont tf = title->font();
    tf.setPointSizeF(tf.pointSizeF() * 0.8);
    title->setFont(tf);
    QLabel *intro = Ui::label(fromAi ? tr("SMILE read your text and split it into sections in delivery order, with the key "
                                         "points it will listen for. Check and adjust them, then confirm.")
                                     : tr("SMILE split your text by its headings and paragraphs. Rename the sections and "
                                          "add key points, then confirm. (Add an AI key for smarter structuring.)"),
                              "secondary");
    intro->setWordWrap(true);

    auto *listHost = new QWidget;
    listHost->setObjectName(QStringLiteral("page"));
    m_list->setContentsMargins(0, 0, 8, 0);
    m_list->setSpacing(10);
    auto *listOuter = new QVBoxLayout(listHost);
    listOuter->setContentsMargins(0, 0, 0, 0);
    listOuter->addLayout(m_list);
    auto *add = new QPushButton(tr("Add section"));
    add->setObjectName(QStringLiteral("subtle"));
    add->setIcon(Icons::icon(Icons::Icon::Add, c.accent, 14));
    add->setCursor(Qt::PointingHandCursor);
    listOuter->addWidget(add, 0, Qt::AlignLeft);
    listOuter->addStretch();
    auto *scroll = new QScrollArea;
    scroll->setWidgetResizable(true);
    scroll->setFrameShape(QFrame::NoFrame);
    scroll->setHorizontalScrollBarPolicy(Qt::ScrollBarAlwaysOff);
    scroll->setWidget(listHost);

    auto *cancel = new QPushButton(tr("Cancel"));
    auto *confirm = new QPushButton(tr("Confirm structure"));
    confirm->setObjectName(QStringLiteral("accent"));
    confirm->setMinimumHeight(38);
    confirm->setMinimumWidth(180);
    confirm->setDefault(true);
    for (QPushButton *b : {cancel, confirm})
        b->setCursor(Qt::PointingHandCursor);
    auto *footer = new QHBoxLayout;
    footer->addWidget(m_summary, 1);
    footer->addWidget(cancel);
    footer->addWidget(confirm);

    auto *layout = new QVBoxLayout(this);
    layout->setContentsMargins(28, 24, 28, 20);
    layout->setSpacing(10);
    layout->addWidget(title);
    if (!presentationType.isEmpty()) {
        QLabel *type = Ui::label(tr("Detected: %1").arg(presentationType));
        type->setStyleSheet(QStringLiteral("background: %1; color: %2; border-radius: 10px; padding: 3px 12px; font-weight: 600;")
                                .arg(Theme::css(c.button), Theme::css(c.accent)));
        type->setSizePolicy(QSizePolicy::Fixed, QSizePolicy::Fixed);
        layout->addWidget(type);
    }
    layout->addWidget(intro);
    layout->addSpacing(4);
    layout->addWidget(scroll, 1);
    layout->addWidget(Ui::divider());
    layout->addLayout(footer);

    for (const AgendaPoint &p : sections)
        addSection(p, fromAi);
    renumber();

    connect(add, &QPushButton::clicked, this, [this] {
        AgendaPoint p;
        p.title = tr("New section");
        p.targetSeconds = 60;
        addSection(p, false);
        renumber();
    });
    connect(cancel, &QPushButton::clicked, this, &QDialog::reject);
    connect(confirm, &QPushButton::clicked, this, &QDialog::accept);
}

void StructureDialog::addSection(const AgendaPoint &point, bool generated)
{
    auto *card = new SectionCard(point, generated, this);
    m_list->addWidget(card);
    connect(card->up, &QPushButton::clicked, this, [this, card] { move(card, -1); });
    connect(card->down, &QPushButton::clicked, this, [this, card] { move(card, +1); });
    connect(card->remove, &QPushButton::clicked, this, [this, card] {
        card->hide();
        card->deleteLater();
        QTimer::singleShot(0, this, &StructureDialog::renumber);
    });
}

void StructureDialog::move(QWidget *card, int delta)
{
    const int from = m_list->indexOf(card);
    const int to = from + delta;
    if (from < 0 || to < 0 || to >= m_list->count())
        return;
    m_list->removeWidget(card);
    m_list->insertWidget(to, card);
    renumber();
}

void StructureDialog::renumber()
{
    int n = 1, total = 0, points = 0;
    for (int i = 0; i < m_list->count(); ++i) {
        auto *card = static_cast<SectionCard *>(m_list->itemAt(i)->widget());
        if (!card || card->isHidden())
            continue;
        card->number->setText(QString::number(n++));
        card->up->setEnabled(i > 0);
        card->down->setEnabled(i < m_list->count() - 1);
        const AgendaPoint p = card->point();
        total += p.targetSeconds;
        points += int(p.keyPoints.size());
    }
    m_summary->setText(plural(n - 1, tr("%1 section"), tr("%1 sections")) + QStringLiteral(" · ")
                       + plural(points, tr("%1 key point"), tr("%1 key points")) + QStringLiteral(" · ")
                       + DurationEdit::format(total, true));
}

Agenda StructureDialog::sections() const
{
    Agenda result;
    for (int i = 0; i < m_list->count(); ++i) {
        auto *card = static_cast<SectionCard *>(m_list->itemAt(i)->widget());
        if (!card || card->isHidden())
            continue;
        const AgendaPoint p = card->point();
        if (!p.title.isEmpty())
            result << p;
    }
    return result;
}
